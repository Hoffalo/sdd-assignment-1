"""Reference data from seed.json, loaded idempotently on every boot (A1 §7.11).

Seeding never duplicates or wipes what users entered: seed-once tables are
filled only while empty, and synced tables are upserted by natural key.
Only reference data lives here; the schema itself is owned by migrations.
"""
import json
from pathlib import Path
from typing import Any

from avdesk_requests.database import Database, Session

SEED_FILE = Path(__file__).resolve().parent.parent / "seed.json"

# The briefing catalog is configuration owned by seed.json, so it follows the
# file on every boot: rows are matched by their natural key and updated.
# Questions missing from the file are removed (nothing references them);
# request types are never removed because requests point at them.
# Diretorias and analysts are not listed: requests point at them by id, so
# they are seeded once into empty tables and never rewritten.
SYNCED_TABLES = {
    "request_types": ("code", False),
    "briefing_questions": ("key", True),
}


def load_seed(path: Path = SEED_FILE) -> dict[str, list[dict[str, Any]]]:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    return {table: rows for table, rows in data.items() if not table.startswith("_")}


def _values(row: dict[str, Any]) -> list[Any]:
    return [json.dumps(v, ensure_ascii=False) if isinstance(v, (list, dict)) else v for v in row.values()]


def _table_names(session: Session) -> set[str]:
    rows = session.execute("SELECT TABLE_NAME AS name FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE = 'BASE TABLE'")
    return {row["name"] for row in rows.fetchall()}


def _writable_columns(session: Session, table: str) -> set[str]:
    # Identity columns are generated by SQL Server, so seed rows never state them.
    rows = session.execute(
        "SELECT COLUMN_NAME AS name FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = %s "
        "AND COLUMNPROPERTY(OBJECT_ID(TABLE_SCHEMA + '.' + TABLE_NAME), COLUMN_NAME, 'IsIdentity') = 0",
        (table,))
    return {row["name"] for row in rows.fetchall()}


def _insert(session: Session, table: str, row: dict[str, Any]) -> None:
    columns = ", ".join(f"[{c}]" for c in row)
    placeholders = ", ".join("%s" for _ in row)
    session.execute(f"INSERT INTO [{table}] ({columns}) VALUES ({placeholders})", _values(row))


def _upsert(session: Session, table: str, row: dict[str, Any], key: str) -> None:
    source = ", ".join(f"%s AS [{c}]" for c in row)
    updates = ", ".join(f"[{c}] = source.[{c}]" for c in row if c != key)
    columns = ", ".join(f"[{c}]" for c in row)
    values = ", ".join(f"source.[{c}]" for c in row)
    # MERGE is SQL Server's upsert; it must end with a semicolon.
    session.execute(
        f"MERGE [{table}] AS target USING (SELECT {source}) AS source ON target.[{key}] = source.[{key}] "
        f"WHEN MATCHED THEN UPDATE SET {updates} "
        f"WHEN NOT MATCHED THEN INSERT ({columns}) VALUES ({values});",
        _values(row))


def _sync(session: Session, table: str, rows: list[dict[str, Any]], key: str, prune: bool) -> None:
    table_columns = _writable_columns(session, table)
    for row in rows:
        # A synced row overwrites the stored one, so a missing column would
        # silently keep a stale value; every column must be stated.
        if set(row) != table_columns:
            raise ValueError(f"seed.json row {row.get(key)!r} in {table} must list exactly {sorted(table_columns)}")
        _upsert(session, table, row, key)
    if prune and rows:
        keys = [row[key] for row in rows]
        session.execute(f"DELETE FROM [{table}] WHERE [{key}] NOT IN ({', '.join('%s' for _ in keys)})", keys)


def load_reference_data(database: Database, seed: dict[str, list[dict[str, Any]]]) -> None:
    with database.connect() as session:
        existing = _table_names(session)
        for table, rows in seed.items():
            # Table names cannot be bound as SQL parameters, so only names that
            # already exist in the schema are allowed into the statement.
            if table not in existing:
                raise ValueError(f"seed.json names unknown table {table!r}")
            if table in SYNCED_TABLES:
                _sync(session, table, rows, *SYNCED_TABLES[table])
            elif not session.execute(f"SELECT TOP 1 1 AS found FROM [{table}]").fetchone():
                for row in rows:
                    _insert(session, table, row)
